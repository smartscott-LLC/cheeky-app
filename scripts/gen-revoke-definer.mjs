// One-time generator: revokes EXECUTE on every SECURITY DEFINER function in
// the public schema from anon + PUBLIC (Supabase advisor: "Public Can Execute
// SECURITY DEFINER Function"). Postgres grants EXECUTE to PUBLIC on new
// functions by default, so every RPC was callable without signing in — and
// several (owner_grant, generate_swag_code) would have been god-mode for
// anyone who found the endpoint. Authenticated (where explicitly granted)
// and service_role grants are untouched — members keep the RPCs the app
// calls; the owner/webhook/service paths keep theirs.
//
// Run: node scripts/gen-revoke-definer.mjs  (output is reviewed, then applied)
import { config } from 'dotenv';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import postgres from 'postgres';

config({ path: 'env.new' });

const sql = postgres(process.env.POSTGRES_URL_NON_POOLING, {
  max: 1,
  ssl: 'require'
});

const rows = await sql`
  select p.oid,
         p.proname,
         pg_get_function_identity_arguments(p.oid) as args,
         coalesce((select string_agg(case when x.grantee = 0 then 'PUBLIC' else r.rolname end, ',' order by 1)
                   from aclexplode(coalesce(p.proacl, acldefault('f', p.oid))) x
                   left join pg_roles r on r.oid = x.grantee
                   where x.privilege_type = 'EXECUTE'), '') as exec_roles
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
    and p.prokind = 'f'
    and p.prosecdef
  order by p.proname, pg_get_function_identity_arguments(p.oid)
`;

const parts = [];
let count = 0;
for (const r of rows) {
  const exposed = /(^|,)PUBLIC(,|$)/.test(r.exec_roles) || /(^|,)anon(,|$)/.test(r.exec_roles);
  if (!exposed) continue;
  count++;
  parts.push(`revoke execute on function public.${r.proname}(${r.args}) from anon, public;`);
}

await sql.end();

const header = `-- Revoke anon/PUBLIC execute on security-definer RPCs (generated by
-- scripts/gen-revoke-definer.mjs, 2026-08-08): ${count} functions were
-- callable without signing in (Postgres's default PUBLIC EXECUTE grant).
-- anon and PUBLIC lose execute; authenticated (where granted) and
-- service_role keep it, so the app, the owner, and the webhook paths are
-- unaffected and members keep every RPC the UI calls.

`;

await writeFile(
  join(process.cwd(), 'supabase', 'migrations', '20260808075000_revoke_anon_execute.sql'),
  header + parts.join('\n') + '\n'
);
console.log(`Wrote 20260808075000_revoke_anon_execute.sql (${count} functions).`);
