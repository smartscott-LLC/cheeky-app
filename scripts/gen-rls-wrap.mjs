// One-time generator: rewrites every public RLS policy whose qual/with-check
// calls auth.uid() / auth.jwt() / auth.role() / current_setting() directly,
// wrapping the call in `(select ...)` so Postgres evaluates it once per
// statement instead of once per row (Supabase's RLS performance guidance).
//
// Reads the live catalog (pg_policy), transforms, and writes the migration.
// Run: node scripts/gen-rls-wrap.mjs
// The output migration is REVIEWED before applying — generated SQL is never
// applied blind.
import { config } from 'dotenv';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import postgres from 'postgres';

config({ path: 'env.new' });

const sql = postgres(process.env.POSTGRES_URL_NON_POOLING, {
  max: 1,
  ssl: 'require'
});

const COMMANDS = { r: 'select', a: 'insert', w: 'update', d: 'delete', '*': 'all' };

// Wrap direct auth/current_setting calls in a scalar subquery. The lookbehind
// skips calls that are already wrapped `(select auth.uid())`.
const WRAP = /(?<!\(select )(auth\.(?:uid|jwt|role)\(\)|current_setting\([^)]*\))/g;

const rows = await sql`
  select c.relname as tablename,
         p.polname as policyname,
         p.polcmd as cmd,
         p.polpermissive as permissive,
         p.polroles as roles,
         pg_get_expr(p.polqual, p.polrelid) as qual,
         pg_get_expr(p.polwithcheck, p.polrelid) as with_check
  from pg_policy p
  join pg_class c on c.oid = p.polrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
  order by c.relname, p.polname
`;

const wrap = (expr) =>
  expr ? expr.replace(WRAP, (m) => `(select ${m})`) : null;

const parts = [];
let changed = 0;

for (const r of rows) {
  const qual = wrap(r.qual);
  const wc = wrap(r.with_check);
  const touched = (r.qual && qual !== r.qual) || (r.with_check && wc !== r.with_check);
  if (!touched) continue;
  changed++;

  const roles =
    (r.roles ?? []).filter((o) => o !== 0).length > 0
      ? ` to ${(r.roles ?? [])
          .filter((o) => o !== 0)
          .map((o) => `"${o}"`)
          .join(', ')}`
      : '';

  parts.push(`-- ${r.tablename}: ${r.policyname}`);
  parts.push(
    `drop policy if exists "${r.policyname}" on public."${r.tablename}";`
  );
  let create =
    `create policy "${r.policyname}" on public."${r.tablename}"\n` +
    `  as ${r.permissive ? 'permissive' : 'restrictive'}\n` +
    `  for ${COMMANDS[r.cmd] ?? 'all'}${roles}\n`;
  if (qual) create += `  using (${qual})\n`;
  if (wc) create += `  with check (${wc})\n`;
  create += ';';
  parts.push(create);
  parts.push('');
}

await sql.end();

const header = `-- RLS perf pass (generated by scripts/gen-rls-wrap.mjs, 2026-08-08):
-- ${changed} policies called auth.uid()/auth.jwt()/auth.role()/current_setting()
-- directly in their quals, forcing per-row evaluation. Each call is now
-- wrapped in a scalar subquery \`(select ...)\` so it computes once per
-- statement. Semantics unchanged — the functions never depend on row values.

`;

await writeFile(
  join(process.cwd(), 'supabase', 'migrations', '20260808070000_rls_auth_wrap.sql'),
  header + parts.join('\n') + '\n'
);
console.log(`Wrote 20260808070000_rls_auth_wrap.sql (${changed} policies).`);
