// One-time generator: pins `search_path` on every public function that
// lacks it (Supabase lint 0011_function_search_path_mutable). Functions with
// no search_path inherit the caller's path — a consistency bug and, for
// SECURITY DEFINER functions, a privilege-escalation vector (a caller could
// put a malicious schema first and hijack unqualified names).
//
// The pin is `pg_catalog, public`: pg_catalog is always implicitly first
// anyway, and public is where all our objects live — unqualified names keep
// resolving exactly as they do today, but a caller can no longer inject a
// schema into the path. Bodies are fully qualified where it matters.
//
// Run: node scripts/gen-fn-search-path.mjs  (output is reviewed, then applied)
import { config } from 'dotenv';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import postgres from 'postgres';

config({ path: 'env.new' });

const sql = postgres(process.env.POSTGRES_URL_NON_POOLING, {
  max: 1,
  ssl: 'require'
});

const rows = await sql`
  select p.oid, p.proname, pg_get_function_identity_arguments(p.oid) as args
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
    and p.prokind = 'f'
    and p.proconfig is null
  order by p.proname
`;

const parts = [];
let fixed = 0;
for (const r of rows) {
  const [{ def }] = await sql.unsafe(
    `select pg_get_functiondef(${r.oid}::oid) as def`
  );
  if (/search_path/.test(def)) continue; // already pinned — skip
  fixed++;
  // pg_get_functiondef emits `AS $function$` as the body delimiter.
  const pinned = def.replace(
    /\nAS \$function\$/,
    '\n SET search_path = pg_catalog, public\nAS $function$'
  ) + ';'; // pg_get_functiondef omits the statement terminator
  parts.push(`-- ${r.proname}(${r.args})`);
  parts.push(pinned);
  parts.push('');
}

await sql.end();

const header = `-- search_path pin pass (generated by scripts/gen-fn-search-path.mjs, 2026-08-08):
-- ${fixed} functions had no search_path and inherited the caller's
-- path (mutable — a consistency risk, and a hijack vector for the SECURITY
-- DEFINER trigger functions). Each now pins \`pg_catalog, public\`.

`;

await writeFile(
  join(process.cwd(), 'supabase', 'migrations', '20260808074000_fn_search_path.sql'),
  header + parts.join('\n') + '\n'
);
console.log(`Wrote 20260808074000_fn_search_path.sql (${parts.length} functions).`);
