// One-time generator: revokes EXECUTE from `authenticated` on the
// service-role-only SECURITY DEFINER functions. Supabase default privileges
// grant EXECUTE to authenticated on every new function, so revoking anon
// alone still left a logged-in member able to call owner_grant or
// generate_swag_code. These functions are called only by the service role
// (owner booth, webhook, AI path, internal/cron) and now require it.
//
// Run: node scripts/gen-revoke-member.mjs  (output is reviewed, then applied)
import { config } from 'dotenv';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import postgres from 'postgres';

config({ path: 'env.new' });

const sql = postgres(process.env.POSTGRES_URL_NON_POOLING, {
  max: 1,
  ssl: 'require'
});

// Service-role-only — the app never calls these with a member session.
const NAMES = [
  'owner_grant',
  'generate_swag_code',
  'flag_swag_request',
  'flag_honeypot_catch',
  'record_character_moment',
  'record_common_moment',
  'record_personal_moment',
  'mark_webhook_processed',
  'award_badge',
  'award_gem',
  'ensure_events',
  'ensure_speed_dating_events',
  'finalize_events',
  'tick_rooftop_events',
  'advance_blind_date',
  'auto_match_rooftop',
  'setup_speed_dating',
  'next_event_minutes',
  'enforce_photo_limit',
  'handle_bot_guard',
  'handle_first_event_badge',
  'handle_first_match_moment',
  'handle_new_profile',
  'handle_new_user'
];

const inList = NAMES.map((n) => `'${n}'`).join(', ');

const rows = await sql.unsafe(`
  select p.proname, pg_get_function_identity_arguments(p.oid) as args
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
    and p.prokind = 'f'
    and p.proname in (${inList})
  order by p.proname, pg_get_function_identity_arguments(p.oid)
`);

await sql.end();

const header = `-- Revoke member (authenticated) execute from service-role-only SECURITY
-- DEFINER functions (generated by scripts/gen-revoke-member.mjs, 2026-08-08).
-- Supabase default privileges grant EXECUTE to authenticated on every new
-- function — so after revoking anon, a logged-in member could still call
-- owner_grant (grant themselves a tier) or generate_swag_code (mint codes).
-- These run only via the service role (owner booth, webhook, AI path,
-- internal/cron) and now require it. Member-facing RPCs are untouched.

`;

let body = header;
for (const r of rows) {
  body += `revoke execute on function public.${r.proname}(${r.args}) from authenticated;\n`;
}

await writeFile(
  join(process.cwd(), 'supabase', 'migrations', '20260808076000_revoke_member_definer.sql'),
  body
);
console.log(`Wrote 20260808076000_revoke_member_definer.sql (${rows.length} functions).`);
